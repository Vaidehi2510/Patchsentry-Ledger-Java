-- Relational core: what the service queries, joins, and scores.
-- Variable-shape evidence (AI findings, limitations) lives in MongoDB.

CREATE TABLE projects (
    id          uuid PRIMARY KEY,
    repository  varchar(201) NOT NULL UNIQUE,
    name        varchar(120) NOT NULL,
    created_at  timestamptz  NOT NULL
);

CREATE TABLE runner_tokens (
    id              uuid PRIMARY KEY,
    project_id      uuid        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    token_hash      varchar(64) NOT NULL UNIQUE,
    display_prefix  varchar(16) NOT NULL,
    created_at      timestamptz NOT NULL,
    revoked_at      timestamptz
);

CREATE INDEX runner_tokens_project_idx ON runner_tokens (project_id);

CREATE TABLE qa_runs (
    record_id       varchar(64)  PRIMARY KEY,
    project_id      uuid         NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    pr_number       integer      NOT NULL CHECK (pr_number > 0),
    pr_title        varchar(300),
    revision        varchar(40)  NOT NULL,
    phase           varchar(40),
    score           integer      NOT NULL CHECK (score BETWEEN 0 AND 100),
    checks_total    integer      NOT NULL,
    checks_passed   integer      NOT NULL,
    outcome         varchar(20)  NOT NULL,
    scoring_policy  varchar(40)  NOT NULL,
    received_at     timestamptz  NOT NULL,
    updated_at      timestamptz  NOT NULL,
    upload_count    integer      NOT NULL,
    version         bigint       NOT NULL
);

CREATE INDEX qa_runs_project_updated_idx ON qa_runs (project_id, updated_at DESC);
CREATE INDEX qa_runs_project_pr_idx ON qa_runs (project_id, pr_number, updated_at DESC);

-- No unique (run_record_id, check_id): re-uploads replace rows, and Hibernate
-- flushes inserts before orphan deletes. Uniqueness is enforced by the validator.
CREATE TABLE check_results (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_record_id  varchar(64)   NOT NULL REFERENCES qa_runs (record_id) ON DELETE CASCADE,
    position       integer       NOT NULL,
    check_id       varchar(100)  NOT NULL,
    name           varchar(300),
    method         varchar(20)   NOT NULL,
    required       boolean       NOT NULL,
    status         varchar(20)   NOT NULL,
    details        varchar(4000)
);

CREATE INDEX check_results_run_idx ON check_results (run_record_id, position);
